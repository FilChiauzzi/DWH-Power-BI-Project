=========================================================
Bronze Layer – Table Definitions
=========================================================
Purpose:
    This script creates raw table structures for the Bronze
    layer of the data platform.

Design rules:
    - ALL source columns are NULL-able: Bronze is a faithful
      raw copy of the source. Data quality is enforced by the
      DQ checks (etl.data_quality_log / etl.rejected), never
      by constraints, so a single bad row cannot fail a load.
    - The only NOT NULL columns are the audit columns the
      warehouse generates itself (dwh_load_date has a DEFAULT,
      so the load procedures do not have to supply it).
    - Each table gets a CLUSTERED COLUMNSTORE index: Bronze is
      append-only, so columnstore gives fast DQ scans (only the
      needed columns are read) and high compression. Tables with
      XML / HIERARCHYID columns (store, person, employee) stay
      heaps, because columnstore does not support those types.

Warning:
    Running this script will DROP existing tables and recreate
    them. All data in these tables will be permanently lost.
*/

